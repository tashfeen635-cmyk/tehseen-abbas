export function seedDb(db) {
  const insert = db.transaction(() => {
    db.prepare("DELETE FROM portfolio_items").run();
    db.prepare("DELETE FROM experience").run();
    db.prepare("DELETE FROM skills").run();
    db.prepare("DELETE FROM awards").run();
    db.prepare("DELETE FROM site_settings").run();

    const pi = db.prepare("INSERT INTO portfolio_items (src, category, sort_order) VALUES (?, ?, ?)");
    let order = 0;
    for (const item of PORTFOLIO) pi.run(item.src, item.category, order++);

    const ex = db.prepare("INSERT INTO experience (icon, title, description, date, color) VALUES (?, ?, ?, ?, ?)");
    for (const e of EXPERIENCE) ex.run(e.icon, e.title, e.description, e.date, e.color);

    const sk = db.prepare("INSERT INTO skills (icon, name, target) VALUES (?, ?, ?)");
    for (const s of SKILLS) sk.run(s.icon, s.name, s.target);

    const aw = db.prepare("INSERT INTO awards (date, title, description) VALUES (?, ?, ?)");
    for (const a of AWARDS) aw.run(a.date, a.title, a.description);

    const st = db.prepare("INSERT INTO site_settings (key, value) VALUES (?, ?)");
    for (const [k, v] of Object.entries(SETTINGS)) st.run(k, v);
  });
  insert();
}
